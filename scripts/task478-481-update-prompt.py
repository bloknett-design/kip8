def update(repo_dir, expect_cur_prefix, new_line3, extra_fields):
    path = os.path.join(BASE, repo_dir,
                        'Системный_промт_для_приложения_КИПиА.md')
    with io.open(path, encoding='utf-8') as f:
        src = f.read()

    i3 = src.index(CUR_MARK)
    i3end = src.index('\n', i3)
    old_line3 = src[i3:i3end]
    if not old_line3.startswith(expect_cur_prefix):
        print('ОШИБКА (%s): текущая версия промта не совпадает с ожиданием: '
              '%s...' % (repo_dir, old_line3[:120]))
        sys.exit(1)

    n_prev_before = src.count(PREV_MARK)

    # (а) удалить самую старую «предыдущую» = ПОСЛЕДНЮЮ по позиции
    # (подводный камень Task 475-480: rindex, не первая)
    if src.count(PREV_MARK) > 2:
        iprev = src.rindex(PREV_MARK)
        iprev_end = src.index('\n', iprev)
        src = src[:iprev] + src[iprev_end + 1:]

    # (б) строка 3 → новая версия + «предыдущая» из старой строки 3
    new_prev = PREV_MARK + ' ' + old_line3[len(CUR_MARK + ' '):]
    src = src[:i3] + new_line3 + '\n' + new_prev + src[i3end:]

    # (в) структурные поля
    for old_s, new_s in extra_fields:
        if old_s not in src:
            print('ОШИБКА (%s): не найдено поле %r' % (repo_dir, old_s[:70]))
            sys.exit(1)
        src = src.replace(old_s, new_s, 1)

    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(src)
    print('OK: %s — версия обновлена (предыдущих: %d → %d)'
          % (repo_dir, n_prev_before, src.count(PREV_MARK)))
    return src


