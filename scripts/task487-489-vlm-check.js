#!/usr/bin/env node
// scripts/task487-489-vlm-check.js — VLM-проверка скриншотов
// переноса партии 487-489 в kip8 (паттерн task489-vlm-check.js
// kip8test; CLI `z-ai vision`). Ожидаем: (1) карточка — полное
// ФИО из трёх слов + «Дата рождения» в конце профиля; (2) форма —
// отдельные поля Фамилия/Имя/Отчество + Дата рождения, единого
// «ФИО» нет; (3) шахматка — краткое ФИО с инициалами; (4) ховер-
// окно «Мероприятия в этот день» — справочный список без кнопок.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8-task487-489-transfer';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000,
       stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['b-card-full-fio-birth.png',
     'Это скриншот веб-приложения табеля (тёмная тема): страница «Работники», карточка работника с блоками профиля. Ответь строго по пунктам: (1) Какой текст в заголовке-шапке блока профиля (ФИО и табельный номер) — приведи дословно. (2) Есть ли в списке профиля строка «Дата рождения» и какое у неё значение? (3) «Дата рождения» стоит в конце списка профиля? (4) ФИО в шапке — полное из трёх слов (фамилия имя отчество) или сокращённое с инициалами?'],
    ['c-edit-form-parts.png',
     'Это скриншот веб-приложения табеля (тёмная тема): шторка-форма правки работника. Ответь строго по пунктам: (1) Есть ли в форме ОТДЕЛЬНЫЕ поля «Фамилия», «Имя», «Отчество»? (2) Есть ли поле «Дата рождения» (ввод даты)? (3) Есть ли ЕДИНОЕ поле с подписью «ФИО» (одно текстовое поле на всё имя)? (4) Какие значения заполнены в полях Фамилия/Имя/Отчество?'],
    ['a-grid-short-fio.png',
     'Это скриншот веб-приложения табеля (тёмная тема): шахматка графика работы, колонка сотрудников слева. Ответь строго: (1) Как показываются имена работников в колонке сотрудников — полностью (три слова) или сокращённо с инициалами? (2) Приведи примеры видимых ФИО. (3) Есть ли где-то на экране полное ФИО из трёх слов?'],
    ['a-hover-popup.png',
     'Это скриншот веб-приложения табеля (тёмная тема): всплывающее окно «Мероприятия в этот день» у ячейки сетки. Ответь строго по пунктам: (1) Заголовок окна? (2) Есть ли в окне строки-мероприятия (код-свотч + название)? (3) Есть ли в окне КАКИЕ-ЛИБО кнопки или кликабельные элементы (галочка, карандаш ✎, крестик ✕, зелёный квадрат-маркер)? (4) Подстрока с датой и ФИО под заголовком — какая?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 1400));
    console.log('');
    if (/Хадасевич|Фамилия|А\. С\.|Мероприятия/.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
