def rd(p):
    return io.open(p, encoding='utf-8').read()


def wr(p, s):
    io.open(p, 'w', encoding='utf-8').write(s)


def rep(s, old, new, tag, cnt=1):
    n = s.count(old)
    chk(n == cnt, '%s: вхождений %d (ожидалось %d)' % (tag, n, cnt))
    return s.replace(old, new)


