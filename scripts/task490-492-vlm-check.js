#!/usr/bin/env node
// scripts/task490-492-vlm-check.js — VLM-проверка скриншотов SMOKE
// переноса Task 490-492 в kip8 (паттерн task492-vlm-check.js; CLI
// `z-ai vision`). Ожидаем то же, что в kip8test: мобильная страница —
// ВНИЗУ фиксированный бар «Все / Избранные», верхних табов нет;
// избранная карточка выделена рамкой/выступом, шрифт у всех
// одинаковый; десктоп — табы сверху, бара нет.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const DIR = '/home/z/my-project/download/kip8-task490-492-smoke';

function vision(file, prompt) {
    const out = execFileSync('z-ai', [
        'vision', '-p', prompt, '-i', path.join(DIR, file)
    ], { encoding: 'utf8', timeout: 120000,
       stdio: ['ignore', 'pipe', 'pipe'] });
    const m = out.match(/"content":\s*"((?:[^"\\]|\\.)*)"/);
    return m ? JSON.parse('"' + m[1] + '"') : out;
}

const shots = [
    ['a-mobile-dark-all.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px). Раздел «Датчики температуры», вкладка «Все». Ответь строго по пунктам: (1) Есть ли ВНИЗУ экрана закреплённая панель с двумя кнопками «Все» и «Избранные» (крупный текст, счётчики)? (2) Карточки-кнопки идут по две в строке? (3) Первая строка — две карточки «50М» рядом, вторая — две «100М» рядом? (4) Все карточки выглядят ОДИНАКОВО (рамка одинаковой толщины, ни одна не выделена градиентом/тенью)? (5) Есть ли НАД списком «Термометры сопротивления» компактные переключатели «Все/Избранные»? — их быть НЕ должно. (6) Не перекрывает ли нижняя панель последнюю карточку?'],
    ['b-mobile-fav-feat.png',
     'Это скриншот мобильного веб-приложения (тёмная тема, 375px), раздел «Датчики температуры», вкладка «Все». Ответь строго по пунктам: (1) РОВНО ОДНА карточка визуально выделена — более толстая синяя рамка, градиент фона и тень, будто «выступает» над остальными? (2) Какая это карточка (обозначение)? (3) На выделенной карточке есть закрашенная звёздочка в углу? (4) Размер шрифта обозначений (50М, 100М…) на выделенной и обычных карточках одинаковый? (5) Внизу экрана панель «Все 17 / Избранные 1»?'],
    ['c-mobile-light-fav-feat.png',
     'Это скриншот мобильного веб-приложения (СВЕТЛАЯ тема, 375px), раздел «Датчики температуры». Ответь строго по пунктам: (1) Внизу экрана панель с кнопками «Все / Избранные»? (2) Текст кнопок читаем (тёмно-синий на светлом фоне, не блёклый)? (3) Единственная карточка выделена рамкой и выглядит «приподнятой» (тень/градиент)? (4) Панель внизу не перекрывает карточку — между ними зазор?'],
    ['d-desktop-top-tabs.png',
     'Это скриншот ДЕСКТОПНОЙ версии (1280px, тёмная тема) раздела «Датчики температуры». Ответь строго по пунктам: (1) Переключатель «Все / Избранные» находится ВВЕРХУ списка (компактная капсула над «Термометры сопротивления»)? (2) Есть ли ВНИЗУ экрана закреплённая панель с крупными кнопками «Все / Избранные»? — её быть НЕ должно. (3) Карточки полные: видны «(Cu50)», «R₀ = 50 Ом», «НСХ»? (4) Карточек в строке больше двух?']
];

let pass = 0, fail = 0;
for (const [file, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    const txt = vision(file, prompt);
    console.log('=== ' + file + ' ===');
    console.log(String(txt).slice(0, 2200));
    console.log('');
    if (/да|есть|одна|одинак/i.test(txt)) pass++;
    else fail++;
}
console.log('VLM: %d passed, %d failed', pass, fail);
if (fail) process.exit(1);
