def replace_line(path, startswith, newline, label):
    with io.open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    hit = [i for i, ln in enumerate(lines) if ln.startswith(startswith)]
    assert len(hit) == 1, '%s: строк-кандидатов %d (ожидалась 1): %r' % (
        label, len(hit), startswith[:60])
    lines[hit[0]] = newline
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('OK %s: %s' % (os.path.basename(os.path.dirname(path)), label))


def replace_exact(path, old, new, label):
    with io.open(path, encoding='utf-8') as f:
        s = f.read()
    n = s.count(old)
    assert n == 1, '%s: вхождений %d (ожидалось 1)' % (label, n)
    s = s.replace(old, new)
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(s)
    print('OK %s: %s' % (os.path.basename(os.path.dirname(path)), label))


