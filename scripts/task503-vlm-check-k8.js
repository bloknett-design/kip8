const CACHE = path.join(DIR, 'vlm-task503-out.json');
let cache = {};
if (fs.existsSync(CACHE)) cache = JSON.parse(fs.readFileSync(CACHE, 'utf8'));

// СКОРИНГ v2: по-вопросно; defectQ — вопрос о дефектах (последний),
// ожидает «нет»; прочие вопросы ожидают «да».
function score(txt, defectQ) {
    const t = String(txt).replace(/\*/g, '');
    const parts = t.split(/(?=\(\s*\d+\s*\))/).map(x => x.trim())
        .filter(x => /^\(\s*\d+\s*\)/.test(x));
    if (parts.length < 2) {
        // ответ не размечен по-вопросно: общий разбор
        if (/(есть|видны?|присутству)\D{0,40}дефект/i.test(t)) return false;
        return true;
    }
    for (const p of parts) {
        const m = p.match(/^\(\s*(\d+)\s*\)\s*(.*)$/);
        if (!m) continue;
        const n = parseInt(m[1], 10);
        const a = m[2].toLowerCase();
        const isDefect = (n === defectQ);
        if (isDefect) {
            // ждём отрицание дефектов
            if (/^да[,.]?\s*( есть| видн| обнаруж| присут)/i.test(a.trim())) return false;
            if (/(есть|видны?|обнаруж|присут)\D{0,30}дефект/i.test(a) &&
                !/не\s+(есть|видны?|обнаруж|присут)/i.test(a)) return false;
        } else {
            // ждём подтверждение
            const hasYes = /(^|[^а-яё])да\b/i.test(a.slice(0, 40));
            const hasNo = /(^|[^а-яё])(нет|не видн|неверно|отсутств|не наблюда|не замече)/i.test(a.slice(0, 60));
            if (hasNo && !hasYes) return false;
        }
    }
    return true;
}

let pass = 0, fail = 0;
for (const [file, defectQ, prompt] of shots) {
    if (!fs.existsSync(path.join(DIR, file))) {
        console.log('нет файла ' + file); fail++; continue;
    }
    let txt = cache[file];
    if (!txt) {
        txt = vision(file, prompt);
        cache[file] = txt;
        fs.writeFileSync(CACHE, JSON.stringify(cache, null, 1));
    }
    const ok = score(txt, defectQ);
    if (ok) { pass++; console.log('+ ' + file); }
    else { fail++; console.log('X ' + file); }
    console.log('    ' + String(txt).replace(/\s+/g, ' ').slice(0, 300));
}

console.log('ИТОГ VLM Task 503: ' + pass + ' OK, ' + fail + ' FAIL');
if (fail) process.exit(1);
