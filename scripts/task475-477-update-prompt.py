CUR_MARK = '> **Версия документа:**'
PREV_MARK = '> **Версия документа (предыдущая):**'


def update(repo_dir, expect_cur_prefix):
    path = os.path.join(BASE, repo_dir,
                        'Системный_промт_для_приложения_КИПиА.md')
    with io.open(path, encoding='utf-8') as f:
        src = f.read()

    i3 = src.index(CUR_MARK)
    i3end = src.index('\n', i3)
    old_line3 = src[i3:i3end]
    if not old_line3.startswith(expect_cur_prefix):
        print('ОШИБКА (%s): текущая версия промта не совпадает с ожиданием: '
              '%s...' % (repo_dir, old_line3[:120]))
        sys.exit(1)

    n_prev_before = src.count(PREV_MARK)

    out = src[:i3] + NEW_LINE3 + src[i3end:]
    # (а) прежняя строка 3 становится «предыдущей» — вставить ПОСЛЕ новой
    out = out.replace(NEW_LINE3 + '\n', NEW_LINE3 + '\n' +
                      PREV_MARK + old_line3[len(CUR_MARK):] + '\n', 1)
    # (б) удалить самую старую «предыдущую» = ПОСЛЕДНЮЮ по позиции
    # (первая по позиции — только что вставленная; подводный камень
    #  первого прогона этого скрипта: удалялась ПЕРВАЯ — терялась
    #  строка, только что ставшая «предыдущей»)
    idxs = [m for m in range(len(out)) if out.startswith(PREV_MARK, m)]
    if len(idxs) > 3:
        oldest = idxs[-1]
        end = out.index('\n', oldest) + 1
        out = out[:oldest] + out[end:]
        # выравнивание пустой строки, если задвоилось
        out = out.replace('\n\n\n', '\n\n', 1) if '\n\n\n' in out else out

    with io.open(path, 'w', encoding='utf-8') as f:
        f.write(out)
    print('OK: %s — версия обновлена (предыдущих: %d → %d)'
          % (repo_dir, n_prev_before, out.count(PREV_MARK)))


